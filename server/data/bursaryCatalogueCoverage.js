function closes(isoDate) {
  return new Date(isoDate)
}

const OCT = '2026-10-31T23:59:59Z'
const NOV = '2026-11-30T23:59:59Z'
const SEP = '2026-09-30T23:59:59Z'
const AUG = '2026-08-31T23:59:59Z'

function row({
  slug,
  name,
  provider,
  type = 'bursary',
  studyFields,
  workSectors = ['any'],
  offersJobAfterGrad = false,
  applicationCloses = OCT,
  applyUrl,
  notes,
}) {
  return {
    slug,
    name,
    provider,
    type,
    studyFields,
    workSectors,
    offersJobAfterGrad,
    applicationCloses: closes(applicationCloses),
    applyUrl,
    notes,
  }
}

